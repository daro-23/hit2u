export function findCardInCatalog(query: {
  name?: string;
  number?: string;
  set?: string;
}): (typeof POKEMON_CATALOG)[0] | undefined {
  const norm = (s?: string) => s?.toLowerCase().replace(/[^a-z0-9]/g, '') || '';
  const queryName = norm(query.name);
  const queryNumber = norm(query.number);
  const querySet = norm(query.set);

  // Exact number + set match
  if (queryNumber && querySet) {
    const match = POKEMON_CATALOG.find(
      c => norm(c.number).includes(queryNumber) && (norm(c.setName).includes(querySet) || norm(c.setSeries).includes(querySet))
    );
    if (match) return match;
  }

  // Name + number match
  if (queryName && queryNumber) {
    const match = POKEMON_CATALOG.find(
      c => norm(c.name).includes(queryName) && norm(c.number).includes(queryNumber)
    );
    if (match) return match;
  }

  // Name match
  if (queryName) {
    const match = POKEMON_CATALOG.find(c => norm(c.name).includes(queryName));
    if (match) return match;
  }

  return undefined;
}
